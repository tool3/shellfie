describe('integration', () => {
  it('handles complex ANSI output (simulated ls --color)', () => {
    const input = [
      '\x1b[1;34mdir1\x1b[0m  \x1b[1;34mdir2\x1b[0m  \x1b[32mfile.txt\x1b[0m',
      '\x1b[1;36mlink\x1b[0m  \x1b[33mwarning.log\x1b[0m',
    ].join('\n');

    const svg = shellfie(input);
    expect(svg).toContain('dir1');
    expect(svg).toContain('dir2');
    expect(svg).toContain('file.txt');
    expect(svg).toContain('link');
    expect(svg).toContain('warning.log');
  });

  it('handles git diff-like output', () => {
    const input = [
      '\x1b[1mdiff --git a/file.ts b/file.ts\x1b[0m',
      '\x1b[36m@@ -1,3 +1,4 @@\x1b[0m',
      ' const a = 1;',
      '\x1b[31m-const b = 2;\x1b[0m',
      '\x1b[32m+const b = 3;\x1b[0m',
      '\x1b[32m+const c = 4;\x1b[0m',
    ].join('\n');

    const svg = shellfie(input, { title: 'git diff' });
    expect(svg).toContain('diff --git');
    expect(svg).toContain('const b = 2');
    expect(svg).toContain('const b = 3');
    expect(svg).toContain('git diff');
  });

  it('handles npm output with colors', () => {
    const input = [
      '\x1b[32mnpm\x1b[0m \x1b[36mWARN\x1b[0m deprecated package@1.0.0',
      '\x1b[32mnpm\x1b[0m \x1b[31mERR!\x1b[0m code ERESOLVE',
    ].join('\n');

    const svg = shellfie(input);
    expect(svg).toContain('npm');
    expect(svg).toContain('WARN');
    expect(svg).toContain('ERR!');
  });
});
